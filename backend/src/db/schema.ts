import { sql } from 'drizzle-orm';
import { index, integer, real, sqliteTable, text, uniqueIndex } from 'drizzle-orm/sqlite-core';

/**
 * Database schema. Documentation: docs/DATA_MODEL.md.
 * Changes: edit this file, run `npm run db:generate`, commit the generated SQL.
 * Never edit a migration that has already been applied.
 *
 * Timestamps are ISO 8601 UTC strings; logical days are YYYY-MM-DD strings.
 */

const now = sql`(strftime('%Y-%m-%dT%H:%M:%fZ', 'now'))`;

const timestamps = {
  createdAt: text('created_at').notNull().default(now),
  updatedAt: text('updated_at').notNull().default(now),
};

export const settings = sqliteTable('settings', {
  key: text('key').primaryKey(),
  value: text('value', { mode: 'json' }).notNull(),
  updatedAt: text('updated_at').notNull().default(now),
});

export const authCredentials = sqliteTable('auth_credentials', {
  /** Always 1 — single user (ADR-001). */
  id: integer('id').primaryKey(),
  passwordHash: text('password_hash').notNull(),
  updatedAt: text('updated_at').notNull().default(now),
});

export const sessions = sqliteTable(
  'sessions',
  {
    /** SHA-256 of the session token; the token itself is never stored. */
    id: text('id').primaryKey(),
    createdAt: text('created_at').notNull().default(now),
    lastSeenAt: text('last_seen_at').notNull().default(now),
    expiresAt: text('expires_at').notNull(),
    deviceLabel: text('device_label'),
  },
  (t) => [index('sessions_expires_at_idx').on(t.expiresAt)],
);

export const trackers = sqliteTable(
  'trackers',
  {
    id: text('id').primaryKey(),
    /** Stable slug, immutable. */
    key: text('key').notNull(),
    module: text('module').notNull(),
    name: text('name').notNull(),
    icon: text('icon'),
    color: text('color'),
    config: text('config', { mode: 'json' })
      .notNull()
      .default(sql`'{}'`),
    configVersion: integer('config_version').notNull().default(1),
    sortOrder: integer('sort_order').notNull().default(0),
    archivedAt: text('archived_at'),
    ...timestamps,
  },
  (t) => [uniqueIndex('trackers_key_uq').on(t.key), index('trackers_module_idx').on(t.module)],
);

export const entries = sqliteTable(
  'entries',
  {
    /** UUIDv7, generated by the client (ADR-004). */
    id: text('id').primaryKey(),
    trackerId: text('tracker_id')
      .notNull()
      .references(() => trackers.id, { onDelete: 'restrict' }),
    occurredAt: text('occurred_at').notNull(),
    endsAt: text('ends_at'),
    localDate: text('local_date').notNull(),
    tzOffsetMin: integer('tz_offset_min').notNull(),
    value: real('value'),
    data: text('data', { mode: 'json' })
      .notNull()
      .default(sql`'{}'`),
    dataVersion: integer('data_version').notNull().default(1),
    note: text('note'),
    source: text('source').notNull().default('manual'),
    sourceRef: text('source_ref'),
    ...timestamps,
    deletedAt: text('deleted_at'),
  },
  (t) => [
    index('entries_tracker_date_idx').on(t.trackerId, t.localDate),
    index('entries_date_idx').on(t.localDate),
    index('entries_tracker_occurred_idx').on(t.trackerId, t.occurredAt),
    uniqueIndex('entries_source_ref_uq')
      .on(t.source, t.sourceRef)
      .where(sql`${t.sourceRef} IS NOT NULL`),
  ],
);

export const goals = sqliteTable(
  'goals',
  {
    id: text('id').primaryKey(),
    trackerId: text('tracker_id')
      .notNull()
      .references(() => trackers.id, { onDelete: 'restrict' }),
    metric: text('metric', { enum: ['sum', 'count', 'avg', 'last', 'duration'] }).notNull(),
    period: text('period', { enum: ['day', 'week', 'month'] }).notNull(),
    comparator: text('comparator', { enum: ['gte', 'lte', 'between'] }).notNull(),
    target: real('target').notNull(),
    targetMax: real('target_max'),
    validFrom: text('valid_from').notNull(),
    validTo: text('valid_to'),
    ...timestamps,
  },
  (t) => [index('goals_tracker_valid_idx').on(t.trackerId, t.validFrom)],
);

export const dashboardWidgets = sqliteTable('dashboard_widgets', {
  id: text('id').primaryKey(),
  widgetType: text('widget_type').notNull(),
  trackerId: text('tracker_id').references(() => trackers.id, { onDelete: 'cascade' }),
  position: integer('position').notNull().default(0),
  size: text('size', { enum: ['sm', 'md', 'lg'] })
    .notNull()
    .default('md'),
  /** Hidden widgets stay configured but are not shown on the dashboard. */
  hidden: integer('hidden', { mode: 'boolean' }).notNull().default(false),
  config: text('config', { mode: 'json' })
    .notNull()
    .default(sql`'{}'`),
  ...timestamps,
});
